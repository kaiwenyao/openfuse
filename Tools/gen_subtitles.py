NOTE_EVENTS = [
    ("0:00:04.00", "0:00:04.80", "缺字体回退：中文仍应显示 · missing font"),
    ("0:00:32.00", "0:00:32.80", "NOTE style uses an uninstalled font name"),
]


def ts(value: str) -> str:
    # ASS wants H:MM:SS.cc
    hours, minutes, rest = value.split(":")
    seconds, centis = rest.split(".")
    return f"{int(hours)}:{int(minutes):02d}:{int(seconds):02d}.{centis}"


def make(language: str) -> str:
    lines = [HEADER]
    for start, end, hans, hant, japanese in CUES:
        chinese = hant if language == "zh-Hant" else hans
        lines.append(
            f"Dialogue: 1,{ts(start)},{ts(end)},JA,,0,0,0,,{japanese}\n"
        )
        lines.append(
            f"Dialogue: 2,{ts(start)},{ts(end)},ZH,,0,0,0,,{chinese}\n"
        )
    for start, end, text in NOTE_EVENTS:
        lines.append(f"Dialogue: 0,{ts(start)},{ts(end)},NOTE,,0,0,0,,{text}\n")
    # Karaoke effect on a separate line to verify ASS tag rendering.
    lines.append(
        "Dialogue: 3,0:00:35.00,0:00:38.00,KARA,,0,0,0,,"
        "{\\k30}逐{\\k30}字{\\k30}出{\\k30}现{\\k30}，{\\k30}颜{\\k30}色{\\k30}测{\\k30}试\n"
    )
    return "".join(lines)


def main() -> None:
    out_dir = os.path.join("Fixtures", "generated")
    os.makedirs(out_dir, exist_ok=True)
    variants = {
        "openfuse-fixture.ass": "zh",
        "openfuse-fixture.zh-Hans.ass": "zh-Hans",
        "openfuse-fixture.zh-Hant.ass": "zh-Hant",
    }
    for filename, language in variants.items():
        path = os.path.join(out_dir, filename)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(make(language))
        print("wrote", path)


if __name__ == "__main__":
    main()
