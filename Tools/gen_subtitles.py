#!/usr/bin/env python3
"""Generate the ASS subtitle fixtures.

Three external variants share one structure so that switching tracks changes
glyphs but not layout:
  openfuse-fixture.ass            no language tag (detection fallback)
  openfuse-fixture.zh-Hans.ass    simplified Chinese + Japanese
  openfuse-fixture.zh-Hant.ass    traditional Chinese + Japanese

Each cue carries its expected timestamp in the text, so after a seek a
reviewer can compare the subtitle content with the burned-in timecode.
The "NOTE" style deliberately names a font that is not installed, which
exercises libass/fontconfig fallback to a system CJK face.
"""
